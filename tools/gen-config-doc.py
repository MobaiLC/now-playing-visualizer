"""Writes docs/CONFIG.md from package/contents/code/schema.json.

CI runs it with --check and fails if the committed file is out of date, so
the option reference can never drift from the schema.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "package" / "contents" / "code" / "schema.json"
OUT = ROOT / "docs" / "CONFIG.md"


def fmt_default(v):
    if v == "" or v == []:
        return "*(empty)*"
    return f"`{json.dumps(v, ensure_ascii=False)}`"


def fmt_values(spec):
    t = spec["type"]
    if t == "enum":
        return "<br>".join(f"`{v['value']}` — {v['label']}" for v in spec["values"])
    if t in ("int", "real"):
        unit = f" {spec['unit']}" if spec.get("unit") else ""
        if spec.get("display") == "percent":
            unit = " (shown as %)"
        return f"{spec['min']} … {spec['max']}{unit}"
    if t == "color":
        return "`#RRGGBB` or `#RRGGBBAA`"
    if t == "colorOrAuto":
        return f"colour, or `{json.dumps(spec['auto'])}` = {spec['autoLabel'].lower()}"
    if t == "colorList":
        return "list of colours"
    if t == "stringList":
        return "list of strings"
    return t


def fmt_when(spec):
    parts = []
    for k, v in spec.get("when", {}).items():
        parts.append(f"`{k}` is {' / '.join(map(str, v)) if isinstance(v, list) else json.dumps(v)}")
    for k, v in spec.get("whenNot", {}).items():
        parts.append(f"`{k}` is not {' / '.join(map(str, v)) if isinstance(v, list) else json.dumps(v)}")
    return "; ".join(parts)


def render():
    schema = json.loads(SCHEMA.read_text())
    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by tools/gen-config-doc.py from schema.json. Do not edit by hand. -->",
        "",
        f"Config version: **{schema['version']}**. Settings live in `~/.config/nowplaying-viz/config.json`:",
        "",
        "```json",
        '{ "version": %d, "preset": "lookas", "audio": { "apps": [] }, "overrides": {}, "presets": {} }' % schema["version"],
        "```",
        "",
        "- `preset` — a built-in preset (`package/contents/code/presets/*.json`) or one of yours.",
        "- `overrides` — any option below, applied on top of the preset, written as nested objects",
        "  (`bars.glow.enabled` → `{\"bars\": {\"glow\": {\"enabled\": true}}}`).",
        "- `presets` — your own presets, same shape as `overrides`.",
        "- `audio.apps` — apps the visualizer listens to (empty = whole system).",
        "",
        "Invalid values are replaced by the default (or clamped to the range) and reported by the",
        "warning icon on the widget. Colours use web notation; `AA` is opacity (`00` invisible, `ff` opaque).",
        "",
    ]
    tabs = {t["id"]: t["label"] for t in schema["tabs"]}
    for group in schema["groups"]:
        opts = [(k, s) for k, s in schema["options"].items() if s["group"] == group["id"]]
        if not opts:
            continue
        lines += [f"## {group['label']}", "", f"*Design → {tabs[group['tab']]}*", "",
                  "| Option | Type | Default | Values | Shown when | Description |",
                  "|---|---|---|---|---|---|"]
        for key, spec in opts:
            note = " *(not in the UI)*" if spec.get("hidden") else ""
            lines.append(f"| `{key}` | {spec['type']} | {fmt_default(spec['default'])} | {fmt_values(spec)} "
                         f"| {fmt_when(spec)} | {spec['label']}{note} |")
        lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/CONFIG.md is out of date: run tools/gen-config-doc.py", file=sys.stderr)
            return 1
        print("docs/CONFIG.md is up to date")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
